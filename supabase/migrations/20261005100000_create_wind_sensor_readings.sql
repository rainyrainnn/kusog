CREATE TABLE IF NOT EXISTS public.wind_sensor_readings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  wind_speed numeric NOT NULL CHECK (wind_speed >= 0),
  wind_direction numeric NOT NULL CHECK (wind_direction >= 0 AND wind_direction < 360),
  recorded_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.wind_sensor_readings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "wind_sensor_readings_select_public" ON public.wind_sensor_readings;
CREATE POLICY "wind_sensor_readings_select_public" ON public.wind_sensor_readings
  FOR SELECT TO anon, authenticated USING (true);

GRANT SELECT ON TABLE public.wind_sensor_readings TO anon, authenticated;
GRANT INSERT ON TABLE public.wind_sensor_readings TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.wind_sensor_readings_id_seq TO service_role;

CREATE INDEX IF NOT EXISTS idx_wind_sensor_readings_recorded_at
  ON public.wind_sensor_readings (recorded_at DESC, id DESC);