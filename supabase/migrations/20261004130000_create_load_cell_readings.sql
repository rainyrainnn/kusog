CREATE TABLE IF NOT EXISTS public.load_cell_readings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raw_value bigint NOT NULL,
  weight_grams numeric,
  weight_kg numeric,
  uplift_force_n numeric,
  recorded_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.load_cell_readings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "load_cell_readings_select_public" ON public.load_cell_readings;
CREATE POLICY "load_cell_readings_select_public" ON public.load_cell_readings
  FOR SELECT TO anon, authenticated USING (true);

GRANT SELECT ON TABLE public.load_cell_readings TO anon, authenticated;
GRANT INSERT ON TABLE public.load_cell_readings TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.load_cell_readings_id_seq TO service_role;

CREATE INDEX IF NOT EXISTS idx_load_cell_readings_recorded_at
  ON public.load_cell_readings (recorded_at DESC, id DESC);