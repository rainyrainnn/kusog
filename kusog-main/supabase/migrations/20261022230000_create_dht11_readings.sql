CREATE TABLE IF NOT EXISTS public.dht11_readings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  temperature_c double precision NOT NULL
    CONSTRAINT dht11_readings_temperature_range CHECK (temperature_c >= 0 AND temperature_c <= 50),
  humidity_percent double precision NOT NULL
    CONSTRAINT dht11_readings_humidity_range CHECK (humidity_percent >= 0 AND humidity_percent <= 100),
  recorded_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.dht11_readings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "dht11_readings_select_public" ON public.dht11_readings;
CREATE POLICY "dht11_readings_select_public" ON public.dht11_readings
  FOR SELECT TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "dht11_readings_insert_sensor" ON public.dht11_readings;
CREATE POLICY "dht11_readings_insert_sensor" ON public.dht11_readings
  FOR INSERT TO anon, authenticated
  WITH CHECK (
    temperature_c >= 0 AND temperature_c <= 50
    AND humidity_percent >= 0 AND humidity_percent <= 100
  );

GRANT SELECT, INSERT ON TABLE public.dht11_readings TO anon, authenticated;
GRANT USAGE ON SEQUENCE public.dht11_readings_id_seq TO anon, authenticated;

CREATE INDEX IF NOT EXISTS idx_dht11_readings_recorded_at
  ON public.dht11_readings (recorded_at DESC, id DESC);
