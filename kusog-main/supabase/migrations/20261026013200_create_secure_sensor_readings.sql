CREATE OR REPLACE FUNCTION public.kusog_insert_dht22_active_reading(
  p_test_record_id uuid,
  p_temperature_c double precision,
  p_humidity_percent double precision,
  p_recorded_at timestamptz
) RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
DECLARE
  session_operator_id uuid;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Sign in before saving DHT22 readings.';
  END IF;
  IF p_temperature_c IS NULL OR p_temperature_c < 0 OR p_temperature_c > 50
    OR p_humidity_percent IS NULL OR p_humidity_percent < 0 OR p_humidity_percent > 100
    OR p_recorded_at IS NULL THEN
    RAISE EXCEPTION 'DHT22 reading is invalid or outside the accepted range.';
  END IF;

  SELECT operator_id
    INTO session_operator_id
  FROM public.test_records
  WHERE id = p_test_record_id
    AND status = 'RUNNING'
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Test session is no longer active.';
  END IF;
  IF session_operator_id IS DISTINCT FROM auth.uid() THEN
    RAISE EXCEPTION 'Test session does not belong to the signed-in user.';
  END IF;

  INSERT INTO public.dht22_readings (
    operator_id, test_record_id, temperature_c, humidity_percent, recorded_at
  ) VALUES (
    session_operator_id, p_test_record_id, p_temperature_c, p_humidity_percent, p_recorded_at
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.kusog_insert_rain_sensor_reading(
  p_test_record_id uuid,
  p_rain_level text,
  p_rain_state text,
  p_rain_24h numeric,
  p_battery_percentage numeric
) RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
DECLARE
  session_operator_id uuid;
  caller_role text;
BEGIN
  caller_role := auth.role();
  IF caller_role <> 'service_role' AND auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Sign in before saving rain sensor readings.';
  END IF;
  IF p_rain_level IS NULL OR p_rain_state IS NULL
    OR (p_rain_24h IS NOT NULL AND p_rain_24h < 0)
    OR (p_battery_percentage IS NOT NULL AND (p_battery_percentage < 0 OR p_battery_percentage > 100)) THEN
    RAISE EXCEPTION 'Rain sensor reading is invalid or outside the accepted range.';
  END IF;

  SELECT operator_id
    INTO session_operator_id
  FROM public.test_records
  WHERE id = p_test_record_id
    AND status = 'RUNNING'
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Test session is no longer active.';
  END IF;
  IF caller_role <> 'service_role' AND session_operator_id IS DISTINCT FROM auth.uid() THEN
    RAISE EXCEPTION 'Test session does not belong to the signed-in user.';
  END IF;

  INSERT INTO public.rain_sensor_readings (
    operator_id, test_record_id, rain_level, rain_state, rain_24h, battery_percentage
  ) VALUES (
    session_operator_id, p_test_record_id, p_rain_level, p_rain_state, p_rain_24h,
    CASE WHEN p_battery_percentage IS NULL THEN NULL ELSE round(p_battery_percentage)::integer END
  );
END;
$$;

