CREATE TABLE IF NOT EXISTS public.bmp280_readings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operator_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  test_record_id uuid NOT NULL REFERENCES public.test_records(id) ON DELETE RESTRICT,
  temperature_c double precision NOT NULL
    CONSTRAINT bmp280_readings_temperature_range CHECK (temperature_c >= -40 AND temperature_c <= 85),
  pressure_hpa double precision NOT NULL
    CONSTRAINT bmp280_readings_pressure_range CHECK (pressure_hpa >= 300 AND pressure_hpa <= 1100),
  recorded_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_bmp280_readings_test_record
  ON public.bmp280_readings (test_record_id, recorded_at DESC, id DESC);

ALTER TABLE public.bmp280_readings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS bmp280_readings_select_authorized ON public.bmp280_readings;
CREATE POLICY bmp280_readings_select_authorized ON public.bmp280_readings
  FOR SELECT TO authenticated
  USING (operator_id = (SELECT auth.uid()));

REVOKE ALL ON TABLE public.bmp280_readings FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.bmp280_readings TO authenticated;
REVOKE ALL ON SEQUENCE public.bmp280_readings_id_seq FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.kusog_insert_bmp280_active_reading(
  p_test_record_id uuid,
  p_temperature_c double precision,
  p_pressure_hpa double precision
) RETURNS TABLE (
  id bigint,
  test_record_id uuid,
  recorded_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  session_operator_id uuid;
BEGIN
  IF p_test_record_id IS NULL
    OR p_temperature_c IS NULL OR p_temperature_c < -40 OR p_temperature_c > 85
    OR p_pressure_hpa IS NULL OR p_pressure_hpa < 300 OR p_pressure_hpa > 1100 THEN
    RAISE EXCEPTION 'BMP280 reading is invalid or outside the accepted range.';
  END IF;

  SELECT tests.operator_id
    INTO session_operator_id
  FROM public.test_records AS tests
  WHERE tests.id = p_test_record_id
    AND tests.status = 'RUNNING'
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN;
  END IF;

  RETURN QUERY
  INSERT INTO public.bmp280_readings (
    operator_id,
    test_record_id,
    temperature_c,
    pressure_hpa
  ) VALUES (
    session_operator_id,
    p_test_record_id,
    p_temperature_c,
    p_pressure_hpa
  )
  RETURNING bmp280_readings.id,
    bmp280_readings.test_record_id,
    bmp280_readings.recorded_at;
END;
$$;

REVOKE ALL ON FUNCTION public.kusog_insert_bmp280_active_reading(uuid, double precision, double precision)
  FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.kusog_insert_bmp280_active_reading(uuid, double precision, double precision)
  TO service_role;

