CREATE TABLE IF NOT EXISTS public.wind_sensor_readings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  test_record_id uuid REFERENCES public.test_records(id) ON DELETE RESTRICT,
  wind_speed numeric NOT NULL CHECK (wind_speed >= 0),
  wind_direction numeric NOT NULL CHECK (wind_direction >= 0 AND wind_direction < 360),
  recorded_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.wind_sensor_readings
  ADD COLUMN IF NOT EXISTS test_record_id uuid
  REFERENCES public.test_records(id) ON DELETE RESTRICT;

CREATE INDEX IF NOT EXISTS idx_wind_sensor_readings_test_record
  ON public.wind_sensor_readings (test_record_id, recorded_at DESC, id DESC);

ALTER TABLE public.wind_sensor_readings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "wind_sensor_readings_select_public" ON public.wind_sensor_readings;
CREATE POLICY wind_sensor_readings_select_public ON public.wind_sensor_readings
  FOR SELECT TO anon, authenticated USING (true);

REVOKE INSERT ON TABLE public.wind_sensor_readings FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT ON TABLE public.wind_sensor_readings TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.wind_sensor_readings_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.kusog_insert_wind_sensor_reading(
  p_test_record_id uuid,
  p_wind_speed numeric,
  p_wind_direction numeric
) RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF p_test_record_id IS NULL OR p_wind_speed IS NULL OR p_wind_speed < 0
    OR p_wind_direction IS NULL OR p_wind_direction < 0 OR p_wind_direction >= 360 THEN
    RAISE EXCEPTION 'Wind reading is outside the accepted range.';
  END IF;

  PERFORM id FROM public.test_records
  WHERE id = p_test_record_id AND status = 'RUNNING'
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Test session is no longer active.';
  END IF;

  INSERT INTO public.wind_sensor_readings (
    test_record_id, wind_speed, wind_direction
  ) VALUES (
    p_test_record_id, p_wind_speed, p_wind_direction
  );
END;
$$;

REVOKE ALL ON FUNCTION public.kusog_insert_wind_sensor_reading(uuid, numeric, numeric)
  FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.kusog_insert_wind_sensor_reading(uuid, numeric, numeric)
  TO service_role;

NOTIFY pgrst, 'reload schema';
